package com.rageval.workbench.classification.domain;

import com.rageval.workbench.dataset.domain.Severity;
import com.rageval.workbench.evaluation.domain.EvaluationEvidence;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.List;
import java.util.Objects;
import java.util.UUID;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * A persisted, evidence-based finding derived from one or more metric results. Findings are
 * generated by rules (Phase 4), not raw metrics re-interpreted at report time — a root cause is
 * only claimed when the evidence actually supports it.
 */
@Entity
@Table(name = "evaluation_finding")
public class EvaluationFinding {

    @Id
    private UUID id;

    @Column(name = "evaluation_run_id", nullable = false)
    private UUID evaluationRunId;

    @Column(name = "test_execution_id", nullable = false)
    private UUID testExecutionId;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 50)
    private FailureCategory category;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Severity severity;

    @Column(nullable = false)
    private String title;

    @Column(nullable = false, columnDefinition = "TEXT")
    private String summary;

    @Column(name = "likely_cause", columnDefinition = "TEXT")
    private String likelyCause;

    @Column(columnDefinition = "TEXT")
    private String recommendation;

    @Column(name = "acceptance_criteria", columnDefinition = "TEXT")
    private String acceptanceCriteria;

    @JdbcTypeCode(SqlTypes.JSON)
    private List<EvaluationEvidence> evidence;

    @Column(name = "human_confirmed", nullable = false)
    private boolean humanConfirmed;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    protected EvaluationFinding() {
        // JPA
    }

    public EvaluationFinding(
            UUID evaluationRunId,
            UUID testExecutionId,
            FailureCategory category,
            Severity severity,
            String title,
            String summary,
            String likelyCause,
            String recommendation,
            String acceptanceCriteria,
            List<EvaluationEvidence> evidence) {
        this.id = UUID.randomUUID();
        this.evaluationRunId = Objects.requireNonNull(evaluationRunId, "evaluationRunId must not be null");
        this.testExecutionId = Objects.requireNonNull(testExecutionId, "testExecutionId must not be null");
        this.category = Objects.requireNonNull(category, "category must not be null");
        this.severity = Objects.requireNonNull(severity, "severity must not be null");
        this.title = Objects.requireNonNull(title, "title must not be null");
        this.summary = Objects.requireNonNull(summary, "summary must not be null");
        this.likelyCause = likelyCause;
        this.recommendation = recommendation;
        this.acceptanceCriteria = acceptanceCriteria;
        this.evidence = evidence != null ? List.copyOf(evidence) : List.of();
        this.humanConfirmed = false;
        this.createdAt = Instant.now();
    }

    public void confirmByHuman() {
        this.humanConfirmed = true;
    }

    public UUID getId() {
        return id;
    }

    public UUID getEvaluationRunId() {
        return evaluationRunId;
    }

    public UUID getTestExecutionId() {
        return testExecutionId;
    }

    public FailureCategory getCategory() {
        return category;
    }

    public Severity getSeverity() {
        return severity;
    }

    public String getTitle() {
        return title;
    }

    public String getSummary() {
        return summary;
    }

    public String getLikelyCause() {
        return likelyCause;
    }

    public String getRecommendation() {
        return recommendation;
    }

    public String getAcceptanceCriteria() {
        return acceptanceCriteria;
    }

    public List<EvaluationEvidence> getEvidence() {
        return evidence;
    }

    public boolean isHumanConfirmed() {
        return humanConfirmed;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
